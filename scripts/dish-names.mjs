// Lists every place where a product name (cốm, mochi, bánh nướng cốm xào, cốm milk tea, bánh dẻo …) is written, so Cam Anh can decide for each
// whether it stays Vietnamese or is translated. Reads content/*.md (builder notes and backups are skipped). Writes DISH-NAMES.md.
// In the dev server the same words are also highlighted in orange on the pages (never in the public build). usage: node scripts/dish-names.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { PROJECT, ROOT } from './_lib.mjs';

const RE = /(?<![\p{L}])(Snow Skin Mooncakes?|Cốm Moon ?Cakes?|Cốm Mùa Trăng|Cốm Trăng Tròn|Cốm Đặc Sản|Cốm Milk Tea|Bánh Nướng Cốm Xào|Mochi Cốm|Cốm Mochi|Bánh Dẻo|Bánh Nướng|Mochi|Cốm)(?![\p{L}])/giu;
const dir = path.join(PROJECT, 'content');
const rows = [];
for (const f of readdirSync(dir).filter((x) => x.endsWith('.md') && !/BEFORE|short-version|it-started-with-culture\.md$/.test(x) || x === 'ch01-it-started-with-culture.md')) {
  readFileSync(path.join(dir, f), 'utf8').split('\n').forEach((line, i) => {
    if (/^BUILD NOTE:/.test(line)) return;
    const found = [...line.matchAll(RE)].map((m) => m[1]);
    if (found.length) rows.push({ f, n: i + 1, found, line: line.replace(/\*\*|\+\+|\{\{|\}\}/g, '').trim().slice(0, 140) });
  });
}
const byTerm = {};
for (const r of rows) for (const t of r.found) (byTerm[t.toLowerCase()] ??= new Set()).add(`${r.f}:${r.n}`);
let md = `# Product names to decide on (Vietnamese or English?)\n\nGenerated by \`node scripts/dish-names.mjs\`. In the dev server these words are highlighted in orange on every page.\n\n## By name\n\n`;
for (const [t, set] of Object.entries(byTerm).sort((a, b) => b[1].size - a[1].size)) md += `- **${t}**: ${set.size} place${set.size > 1 ? 's' : ''}\n`;
md += `\n## Every place\n\n| File | Line | Names | Text |\n|---|---|---|---|\n`;
for (const r of rows) md += `| ${r.f} | ${r.n} | ${[...new Set(r.found)].join(', ')} | ${r.line.replace(/\|/g, '/')} |\n`;
writeFileSync(path.join(ROOT, 'DISH-NAMES.md'), md);
console.log(rows.length, 'lines,', Object.keys(byTerm).length, 'different names');
