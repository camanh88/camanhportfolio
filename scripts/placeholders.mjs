// Collects every [square-bracket] placeholder from content/*.md into site/PLACEHOLDERS.md.
// BUILD NOTE lines and the builder-only "Image map" section are ignored.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { PROJECT, ROOT } from './_lib.mjs';

const dir = path.join(PROJECT, 'content');
const rows = [];
const USED = ['cover.md', 'contents.md', 'intro-skills.md', 'ch01-it-started-with-culture.md', 'ch02-becoming-whole-in-fb.md', 'ch03-different-kitchens.md', 'ch04-off-the-menu.md', 'ch05-why-marou.md', 'nav.md', 'side-pages.md']; // files the site renders
for (const f of readdirSync(dir).filter((x) => USED.includes(x)).sort()) {
  let skip = false, heading = '';
  readFileSync(path.join(dir, f), 'utf8').split('\n').forEach((line, i) => {
    const h = /^#{1,3}\s+(.*)/.exec(line);
    if (h) { heading = h[1]; skip = /^image map/i.test(h[1]); }
    if (skip || /^BUILD NOTE:/.test(line)) return;
    for (const m of line.matchAll(/\[([^\]]+)\](?!\()/g)) rows.push({ f, n: i + 1, heading, text: m[0] });
  });
}
const esc = (s) => s.replace(/\|/g, '\\|');
const out = [
  '# Open placeholders',
  '',
  'Generated by `npm run placeholders` (also runs before every build). Do not edit by hand: fill them in inside `content/` and rebuild.',
  '',
  `${rows.length} placeholders.`,
  '',
  '| File | Line | Under heading | Placeholder |',
  '|------|------|---------------|-------------|',
  ...rows.map((r) => `| content/${r.f} | ${r.n} | ${esc(r.heading)} | ${esc(r.text)} |`),
  '',
].join('\n');
writeFileSync(path.join(ROOT, 'PLACEHOLDERS.md'), out);
console.log(`PLACEHOLDERS.md: ${rows.length} placeholders`);
